// Run: npx tsx apps/api/src/centralAreas/areas.test.ts
import assert from 'node:assert/strict';
import { pointInArea, validAreaPolygon, areaPolygonSchema, centralAreaSchema, type AreaPoint } from '@taxi/shared';
const square = [{ lat: 0, lng: 0 }, { lat: 0, lng: 2 }, { lat: 2, lng: 2 }, { lat: 2, lng: 0 }];
assert(validAreaPolygon(square));
assert(validAreaPolygon([...square].reverse()));
for (const point of [{ lat: 1, lng: 1 }, ...square, { lat: 0, lng: 1 }]) assert(pointInArea(point, square));
assert(!pointInArea({ lat: 3, lng: 1 }, square));
const concave = [...square.slice(0, 3), { lat: 1, lng: 1 }, square[3]];
assert(validAreaPolygon(concave));
assert(!pointInArea({ lat: 1.8, lng: 1 }, concave));
assert(!validAreaPolygon([square[0], square[2], square[1], square[3]]));
assert(!validAreaPolygon([...square, square[0]]));
assert(!validAreaPolygon([{ lat: 0, lng: 0 }, { lat: 0, lng: 1 }, { lat: 0, lng: 2 }]));
assert(!validAreaPolygon([{ lat: 0, lng: 0 }, { lat: 0, lng: 2 }, { lat: 0, lng: 1 }, { lat: 2, lng: 0 }]));
assert(!validAreaPolygon(square.slice(0, 2)));
const circle = (size: number): AreaPoint[] => Array.from({ length: size }, (_, i) => ({ lat: Math.sin(i / size * Math.PI * 2), lng: Math.cos(i / size * Math.PI * 2) }));
assert(areaPolygonSchema.safeParse(circle(100)).success);
assert(!areaPolygonSchema.safeParse(circle(101)).success);
assert(!areaPolygonSchema.safeParse([{ lat: NaN, lng: 0 }, ...square.slice(1)]).success);
assert(!areaPolygonSchema.safeParse([{ lat: 91, lng: 0 }, ...square.slice(1)]).success);
assert(!areaPolygonSchema.safeParse([{ lat: 0, lng: Infinity }, ...square.slice(1)]).success);
assert(!centralAreaSchema.safeParse({ centralId: 'bad', name: ' ', color: '<script>', polygon: square }).success);

process.env.DATABASE_URL = 'postgresql://test:test@localhost:1/test';
process.env.JWT_ACCESS_SECRET = 'area-test-access';
process.env.JWT_REFRESH_SECRET = 'area-test-refresh';
const { buildAreaPresence } = await import('./presence.js');
const now = Date.now();
const area = { id: 'area', centralId: 'company', name: 'Centro', color: '#f5b301', polygon: square };
const taxi = { driverId: 'driver', centralId: 'company', fullName: 'Test', taxiNumber: '1', status: 'BUSY' as const, lat: 1, lng: 1, recordedAt: new Date(now - 1000).toISOString() };
assert.equal(buildAreaPresence([area], [taxi], now).taxis.length, 1);
assert.equal(buildAreaPresence([area], [{ ...taxi, centralId: 'other' }], now).taxis.length, 0);
assert.equal(buildAreaPresence([area], [{ ...taxi, status: 'OFFLINE' }], now).taxis.length, 0);
assert.equal(buildAreaPresence([area], [{ ...taxi, lat: 3 }], now).taxis.length, 0);
assert.equal(buildAreaPresence([area], [{ ...taxi, recordedAt: new Date(now - 60000).toISOString() }], now).taxis.length, 0);
assert.equal(buildAreaPresence([area], [{ ...taxi, recordedAt: new Date(now - 59999).toISOString() }], now).taxis.length, 1);
assert.equal(buildAreaPresence([area], [{ ...taxi, recordedAt: new Date(now + 1).toISOString() }], now).taxis.length, 0);
assert.deepEqual(buildAreaPresence([area, { ...area, id: 'overlap' }], [taxi], now).taxis[0].areaIds, ['area', 'overlap']);
console.log('Central areas: geometry, boundaries, overlaps, tenant scope and 60-second expiry OK');
